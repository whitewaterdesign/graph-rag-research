    def content(self, eyebrow, title, blocks):
        """Body text + bullets, split across continuation slides if too tall."""
        pages, page, used = [], [], 0.0
        avail = BODY_BOT - BODY_TOP
        for b in blocks:
            if b["t"] == "para":
                h = est_height(b["text"], CW, 15) + 0.2
            elif b["t"] == "quote":
                h = est_height_serif(b["text"], CW - 0.30, 17) + 0.34
            elif b["t"] == "bullets":
                h = sum(bullet_height(it) for it in b["items"]) + 0.14
            else:
                h = 0.4
            if used + h > avail and page:
                pages.append(page)
                page, used = [], 0.0
            page.append(b)
            used += h
        if page:
            pages.append(page)

        for pi, pg in enumerate(pages):
            s = self.new()
            y = self.chrome(s, eyebrow, title + ("" if pi == 0 else " (cont.)"))
            for b in pg:
                if b["t"] == "para":
                    h = est_height(b["text"], CW, 15) + 0.14
                    tf = textbox(s, ML, y, CW, h)
                    set_para(tf.paragraphs[0], runs_of(b["text"]), 15, BODY, line=1.34)
                    y += h + 0.20
                elif b["t"] == "quote":
                    h = est_height_serif(b["text"], CW - 0.30, 17, line=1.34) + 0.10
                    rect(s, ML, y, 0.05, h, fill=OCHRE)
                    tf = textbox(s, ML + 0.30, y, CW - 0.30, h)
                    set_para(tf.paragraphs[0], runs_of(b["text"]), 17, SLATE_DK,
                             font=HFONT, italic=True, line=1.34)
                    y += h + 0.24
                elif b["t"] == "bullets":
                    for it in b["items"]:
                        x = ML + it["level"] * 0.34
                        rect(s, x + 0.04, y + 0.115, 0.10, 0.10,
                             fill=OCHRE if it["level"] == 0 else SLATE, adj=0.5)
                        tf = textbox(s, x + 0.34, y, bullet_width(it), bullet_height(it))
                        set_para(tf.paragraphs[0], runs_of(it["text"]), 15, BODY, line=1.30)
                        y += bullet_height(it)
                    y += 0.12

    def cards(self, eyebrow, title, units, lede=""):
        """Grid of up to 6 short sections, under an optional intro line."""
        s = self.new()
        top = self.chrome(s, eyebrow, title)
        if lede:
            lh = est_height(lede, CW, 14) + 0.10
            tf = textbox(s, ML, top - 0.06, CW, lh)
            set_para(tf.paragraphs[0], runs_of(lede), 14, MUTED, line=1.32)
            top += lh + 0.22
        n = len(units)
        cols = 3 if n > 4 else (n if n <= 3 else 2)
        rows = math.ceil(n / cols)
        gap = 0.32
        cw = (CW - gap * (cols - 1)) / cols
        avail = BODY_BOT - top
        ch = min(3.35, avail) if rows == 1 else (avail - gap * (rows - 1)) / rows
        for k, u in enumerate(units):
            r, c = divmod(k, cols)
            x = ML + c * (cw + gap)
            y = top + r * (ch + gap)
            accent = ACCENTS[k % len(ACCENTS)]
            rect(s, x, y, cw, ch, fill=CARD_BG, line=RULE, line_w=1.0)
            rect(s, x, y, 0.075, ch, fill=accent, shape=MSO_SHAPE.RECTANGLE)
            tf = textbox(s, x + 0.34, y + 0.28, cw - 0.62, 0.62)
            set_para(tf.paragraphs[0], u["head"], 15, SLATE_DK, font=HFONT, bold=True, line=1.12)
            body = " ".join(b["text"] for b in u["blocks"] if b["t"] == "para")
            bl = [b for b in u["blocks"] if b["t"] == "bullets"]
            yy = y + 0.28 + 0.62 + (0.10 if body else 0)
            if body:
                bh = ch - (yy - y) - 0.24
                bsize = 12.0
                while bsize > 10.0 and est_height(body, cw - 0.62, bsize, 1.30) > bh:
                    bsize -= 0.5
                tf = textbox(s, x + 0.34, yy, cw - 0.62, bh)
                set_para(tf.paragraphs[0], runs_of(body), bsize, MUTED, line=1.30)
            for b in bl:
                for it in b["items"]:
                    tf = textbox(s, x + 0.34, yy, cw - 0.62, 0.26)
                    set_para(tf.paragraphs[0], "— " + it, 12, MUTED)
                    yy += 0.28

    def pair(self, eyebrow, title, spec):
        """Side-by-side cards, one per bold-led paragraph, with an optional
        opening line above them and a closing kicker below."""
        cards, lede, kicker = spec["cards"], spec["lede"], spec["kicker"]
        s = self.new()
        top = self.chrome(s, eyebrow, title)
        bot = BODY_BOT
        if lede:
            lh = est_height(lede, CW, 14) + 0.10
            tf = textbox(s, ML, top - 0.06, CW, lh)
            set_para(tf.paragraphs[0], runs_of(lede), 14, MUTED, line=1.32)
            top += lh + 0.24
        if kicker:
            kh = est_height_serif(kicker, CW - 0.30, 16, line=1.34) + 0.10
            bot -= kh + 0.34
            rect(s, ML, bot + 0.34, 0.05, kh, fill=OCHRE)
            tf = textbox(s, ML + 0.30, bot + 0.34, CW - 0.30, kh)
            set_para(tf.paragraphs[0], runs_of(kicker), 16, SLATE_DK,
                     font=HFONT, italic=True, line=1.34)
        gap, n = 0.42, len(cards)
        cw = (CW - gap * (n - 1)) / n
        h = bot - top
        hsize = 20 if n < 4 else 18

        # One head band for the whole row, sized to the tallest heading, so every
        # card's body starts on the same line.
        hh = max([0.50] + [est_height_serif(c["head"], cw - 0.80, hsize) + 0.08
                           for c in cards])

        def head_height(c):
            return hh

        def fill_height(c, size):
            """How tall a card's contents run at this body size."""
            y = 0.42 + head_height(c) + 0.10
            if c["text"]:
                y += est_height(c["text"], cw - 0.80, size) + 0.26
            for it in c["bullets"]:
                y += est_height(it["text"], cw - 1.10, size - 1) + 0.18
            return y + 0.34

        size = 14 if n < 4 else 13
        while size > 10 and max(fill_height(c, size) for c in cards) > h:
            size -= 1

        for k, c in enumerate(cards):
            x = ML + k * (cw + gap)
            accent = ACCENTS[k % len(ACCENTS)]
            rect(s, x, top, cw, h, fill=CARD_BG, line=RULE, line_w=1.0)
            rect(s, x, top, cw, 0.075, fill=accent, shape=MSO_SHAPE.RECTANGLE)
            hh = head_height(c)
            tf = textbox(s, x + 0.40, top + 0.42, cw - 0.80, hh)
            set_para(tf.paragraphs[0], c["head"], hsize, accent,
                     font=HFONT, bold=True, line=1.12)
            y = top + 0.42 + hh + 0.10
            if c["text"]:
                bh = est_height(c["text"], cw - 0.80, size) + 0.10
                tf = textbox(s, x + 0.40, y, cw - 0.80, bh)
                set_para(tf.paragraphs[0], c["body"], size, BODY, line=1.36)
                y += bh + 0.16
            for it in c["bullets"]:
                ih = est_height(it["text"], cw - 1.10, size - 1) + 0.06
                rect(s, x + 0.44, y + 0.11, 0.09, 0.09, fill=accent, adj=0.5)
                tf = textbox(s, x + 0.72, y, cw - 1.12, ih)
                set_para(tf.paragraphs[0], runs_of(it["text"]), size - 1, BODY, line=1.30)
                y += ih + 0.12

    def steps(self, eyebrow, title, items, lede=""):
        """A numbered sequence: one chip-and-text row per step."""
        s = self.new()
        top = self.chrome(s, eyebrow, title)
        if lede:
            h = est_height(lede, CW, 14) + 0.10
            tf = textbox(s, ML, top - 0.06, CW, h)
            set_para(tf.paragraphs[0], runs_of(lede), 14, MUTED, line=1.32)
            top += h + 0.22
        n = len(items)
        size = 15 if n <= 5 else 14
        tw = CW - 0.76
        # Rows are as tall as the step that sits in them, so a step that wraps
        # onto two lines does not leave a broken connector behind it.
        def measure(size):
            rows = [max(0.52, est_height(it["text"], tw, size, line=1.30)) for it in items]
            return rows, (BODY_BOT - top - sum(rows)) / max(1, n - 1)

        rows, pad = measure(size)
        while size > 11 and pad < 0.14:
            size -= 1
            rows, pad = measure(size)
        pad = min(0.34, max(0.08, pad))
        y = top
        for k, it in enumerate(items):
            rect(s, ML, y, 0.44, 0.44, fill=ACCENTS[k % len(ACCENTS)], adj=0.5)
            tf = textbox(s, ML, y + 0.055, 0.44, 0.34)
            set_para(tf.paragraphs[0], str(k + 1), 15, WHITE, font=HFONT,
                     bold=True, align=PP_ALIGN.CENTER)
            if k < n - 1:
                rect(s, ML + 0.205, y + 0.46, 0.03, rows[k] + pad - 0.48, fill=RULE)
            tf = textbox(s, ML + 0.76, y + 0.02, tw, rows[k])
            set_para(tf.paragraphs[0], runs_of(it["text"]), size, BODY, line=1.30)
            y += rows[k] + pad

    def figure(self, eyebrow, title, src, caption, lede=""):
        s = self.new()
        top = self.chrome(s, eyebrow, title)
        if lede:
            h = est_height(lede, CW, 14) + 0.10
            tf = textbox(s, ML, top - 0.10, CW, h)
            set_para(tf.paragraphs[0], runs_of(lede), 14, MUTED, line=1.32)
            top += h + 0.12
        path = os.path.join(ROOT, src)
        if not os.path.exists(path):
            tf = textbox(s, ML, BODY_TOP, CW, 0.4)
            set_para(tf.paragraphs[0], f"[missing image: {src}]", 14, CROSS, italic=True)
            return
        box_h = (BODY_BOT - top) - (0.42 if caption else 0)
        pic = s.shapes.add_picture(path, Inches(ML), Inches(top), width=Inches(CW))
        if pic.height > Inches(box_h):
            pic._element.getparent().remove(pic._element)
            pic = s.shapes.add_picture(path, Inches(ML), Inches(top), height=Inches(box_h))
        pic.left = Emu(int(Inches(ML) + (Inches(CW) - pic.width) / 2))
        pic.top = Emu(int(Inches(top) + (Inches(box_h) - pic.height) / 2))
        if caption:
            tf = textbox(s, ML, BODY_BOT - 0.34, CW, 0.32)
            set_para(tf.paragraphs[0], caption, 11.5, MUTED, italic=True, align=PP_ALIGN.CENTER)

    def table(self, eyebrow, title, head, rows):
        nc = len(head)
        vmargin, hdr, pad = 0.03, 0.46, 0.28

        def cell_text(row, c):
            return clean_inline(row[c]) if c < len(row) else ""

        # Columns share the width in proportion to the text they carry, so a
        # column of one-word labels cannot crowd out a column of prose.
        weights = []
        for c in range(nc):
            lens = [len(cell_text(r, c)) for r in rows] or [0]
            weights.append(max(8.0, len(clean_inline(head[c])), sum(lens) / len(lens)))
        widths = [CW * w / sum(weights) for w in weights]
        widths = [max(0.95, w) for w in widths]
        widths = [w * CW / sum(widths) for w in widths]

        def row_height(row, size):
            """Tallest cell in the row once its text wraps to the column width."""
            n = max(_line_count(cell_text(row, c),
                                max(4, ((widths[c] - pad) * 72) / (0.505 * size)))
                    for c in range(nc)) if nc else 1
            return n * size * 1.30 / 72 + 2 * vmargin + 0.10

        avail = BODY_BOT - BODY_TOP - hdr
        bsize = 13.0
        while bsize > 9.5 and sum(row_height(r, bsize) for r in rows) > avail:
            bsize -= 0.5

        # Pack by measured height, so a table of wrapping prose splits onto a
        # second slide instead of running off the bottom of the first.
        chunks, chunk, used = [], [], 0.0
        for r in rows:
            h = row_height(r, bsize)
            if chunk and (used + h > avail or len(chunk) >= MAX_TABLE_ROWS):
                chunks.append(chunk)
                chunk, used = [], 0.0
            chunk.append(r)
            used += h
        chunks.append(chunk)

        for ci, chunk in enumerate(chunks):
            s = self.new()
            top = self.chrome(s, eyebrow, title + ("" if ci == 0 else " (cont.)"))
            nr = len(chunk) + 1
            heights = [row_height(r, bsize) for r in chunk]
            th = hdr + sum(heights)
            gf = s.shapes.add_table(nr, nc, Inches(ML), Inches(top), Inches(CW), Inches(th))
            tbl = gf.table
            tbl.first_row = True
            for c in range(nc):
                tbl.columns[c].width = Inches(widths[c])
            tbl.rows[0].height = Inches(hdr)
            for r in range(1, nr):
                tbl.rows[r].height = Inches(heights[r - 1])

            for c, htxt in enumerate(head):
                cell = tbl.cell(0, c)
                cell.fill.solid()
                cell.fill.fore_color.rgb = SLATE_DK
                cell.margin_left = cell.margin_right = Inches(0.14)
                cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                set_para(cell.text_frame.paragraphs[0], runs_of(htxt), bsize - 0.5, WHITE,
                         bold=True, align=PP_ALIGN.LEFT if c == 0 else PP_ALIGN.CENTER)

            for r, row in enumerate(chunk, start=1):
                for c in range(nc):
                    raw = row[c] if c < len(row) else ""
                    cell = tbl.cell(r, c)
                    cell.fill.solid()
                    cell.fill.fore_color.rgb = WHITE if r % 2 else RGBColor(0xF3, 0xF6, 0xF8)
                    cell.margin_left = cell.margin_right = Inches(0.14)
                    cell.margin_top = cell.margin_bottom = Inches(vmargin)
                    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                    txt = clean_inline(raw)
                    # runs, so **bold** inside a cell renders instead of printing
                    content, col, size, bold = runs_of(raw), BODY, bsize, False
                    if txt in ("✅", "✓", "yes"):
                        content, col, size, bold = "✓", TICK, bsize + 3, True
                    elif txt in ("❌", "✗", "no"):
                        content, col, size, bold = "✗", CROSS, bsize + 3, True
                    set_para(cell.text_frame.paragraphs[0], content, size, col, bold=bold,
                             align=PP_ALIGN.LEFT if c == 0 else PP_ALIGN.CENTER)

    def closing(self, text):
        s = self.new(dark=True)
        tf = textbox(s, ML, 1.68, CW * 0.7, 0.3)
        set_para(tf.paragraphs[0], "WHERE THIS LEAVES US", 11, OCHRE, bold=True, spacing=1.8)
        tf = textbox(s, ML, 2.30, CW * 0.74, 3.6)
        set_para(tf.paragraphs[0], runs_of(text), 22, WHITE, font=HFONT, line=1.42)
        self.node_motif(s, 9.9, 5.55, scale=0.78)

    def bibliography(self, entries, eyebrow):
        """Numbered reference list. Two columns, each read top to bottom."""
        per_slide = 10
        chunks = [entries[i:i + per_slide] for i in range(0, len(entries), per_slide)]
        for ci, chunk in enumerate(chunks):
            s = self.new()
            top = self.chrome(s, eyebrow, "References")
            gap = 0.50
            cw = (CW - gap) / 2
            rows = int(math.ceil(len(chunk) / 2.0))
            eh = (BODY_BOT - top) / max(1, rows)
            tw = cw - 0.46
            for k, rec in enumerate(chunk):
                col, row = divmod(k, rows)      # column-major, so numbering reads down
                x, y = ML + col * (cw + gap), top + row * eh
                tf = textbox(s, x, y, 0.40, 0.34)
                set_para(tf.paragraphs[0], f"{ci * per_slide + k + 1:02d}", 12,
                         ACCENTS[k % len(ACCENTS)], font=HFONT, bold=True)
                # Title and meta share one frame so the meta always follows the
                # last line of the title, however the title happens to wrap.
                size = 12.0
                while size > 9.5 and est_height_serif(rec["title"], tw, size) > eh - 0.30:
                    size -= 0.5
                tf = textbox(s, x + 0.46, y - 0.02, tw, eh - 0.10)
                set_para(tf.paragraphs[0], rec["title"], size, SLATE_DK, font=HFONT,
                         bold=True, line=1.18)
                set_para(tf.add_paragraph(), reference_meta(rec), 10, MUTED,
                         space_before=5)

    def save(self):
        self.prs.save(OUT)


