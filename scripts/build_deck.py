def textbox(slide, x, y, w, h, anchor=MSO_ANCHOR.TOP):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    return tf


def set_para(p, text_or_runs, size, color, font=BFONT, bold=False, italic=False,
             space_after=0, space_before=0, line=1.28, align=PP_ALIGN.LEFT, spacing=None):
    p.alignment = align
    p.space_after = Pt(space_after)
    p.space_before = Pt(space_before)
    p.line_spacing = line
    runs = text_or_runs if isinstance(text_or_runs, list) else [(text_or_runs, bold, italic)]
    for t, b, i in runs:
        if not t:
            continue
        r = p.add_run()
        r.text = t
        r.font.size = Pt(size)
        r.font.color.rgb = color
        r.font.name = font
        r.font.bold = b or bold
        r.font.italic = i or italic
        if spacing is not None:
            r.font._rPr.set("spc", str(int(spacing * 100)))
    return p


def rect(slide, x, y, w, h, fill=None, line=None, shape=MSO_SHAPE.ROUNDED_RECTANGLE,
         line_w=1.0, adj=0.06):
    s = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    if shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        try:
            s.adjustments[0] = adj
        except Exception:
            pass
    if fill is None:
        s.fill.background()
    else:
        s.fill.solid()
        s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
        s.line.width = Pt(line_w)
    # shadow.inherit = False writes the empty <a:effectLst/> that kills the
    # shadow; appending a second one makes the file invalid and PowerPoint then
    # offers to "repair" it. Dropping p:style removes the theme's shadow too.
    s.shadow.inherit = False
    style = s._element.find(qn("p:style"))
    if style is not None:
        s._element.remove(style)
    return s


def bg(slide, color):
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = color


def _line_count(text, cpl):
    """Lines a greedy word-wrap would use. Counting characters alone under-counts
    a narrow column, where one long word ("Semantic-based") takes a line to
    itself and leaves the rest of it empty."""
    cpl = max(1, int(cpl))
    lines, cur = 1, 0
    for word in text.split():
        if cur == 0:
            used = len(word)
        elif cur + 1 + len(word) <= cpl:
            cur += 1 + len(word)
            continue
        else:
            lines += 1
            used = len(word)
        if used > cpl:                      # a word wider than the column
            lines += (used - 1) // cpl
            cur = used - ((used - 1) // cpl) * cpl
        else:
            cur = used
    return lines


def est_height(text, width_in, size_pt, line=1.28):
    """Conservative rendered height in inches for wrapped body text."""
    cpl = max(4, (width_in * 72) / (0.505 * size_pt))
    return _line_count(text, cpl) * size_pt * line / 72.0


def bullet_width(item):
    return CW - 0.34 - item["level"] * 0.34


def bullet_height(item):
    """A bullet is as tall as it wraps -- a long one must not sit on the next."""
    return max(0.30, est_height(item["text"], bullet_width(item), 15, line=1.30)) + 0.06


def est_height_serif(text, width_in, size_pt, line=1.18, widen=1.36):
    """As est_height, for headings set in HFONT. est_height is calibrated for
    Calibri; Georgia sets wider and wraps early on long words, so widen the
    per-character width only -- the line height itself is unchanged."""
    cpl = max(4, (width_in * 72) / (0.505 * size_pt * widen))
    return _line_count(text, cpl) * size_pt * line / 72.0


