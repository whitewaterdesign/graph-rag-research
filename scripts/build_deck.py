class Deck:
    def __init__(self, title):
        self.prs = Presentation()
        self.prs.slide_width = Inches(SW)
        self.prs.slide_height = Inches(SH)
        self.blank = self.prs.slide_layouts[6]
        self.title = title
        self.n = 0
        self.section_titles = set()

    def new(self, dark=False):
        s = self.prs.slides.add_slide(self.blank)
        bg(s, INK if dark else PAGE_BG)
        return s

    def chrome(self, slide, eyebrow, title):
        """Eyebrow + title + footer rule, used on every light content slide."""
        self.n += 1
        # A title already used in this section is a continuation, even if
        # another slide (a figure, say) came between the two.
        if title in self.section_titles:
            title += " (cont.)"
        else:
            self.section_titles.add(title)
        if eyebrow:
            tf = textbox(slide, ML, 0.62, CW, 0.26)
            set_para(tf.paragraphs[0], eyebrow.upper(), 10, SLATE, bold=True, spacing=1.4)
        lines = max(1, math.ceil(len(title) / 52.0))
        tf = textbox(slide, ML, 0.92, CW, 0.52 * lines + 0.10)
        set_para(tf.paragraphs[0], title, 30, SLATE_DK, font=HFONT, bold=True, line=1.06)

        ln = rect(slide, ML, 6.92, CW, 0.012, fill=RULE, shape=MSO_SHAPE.RECTANGLE)
        tf = textbox(slide, ML, 7.02, CW / 2, 0.24)
        set_para(tf.paragraphs[0], FOOTER, 9, MUTED)
        tf = textbox(slide, ML + CW / 2, 7.02, CW / 2, 0.24)
        set_para(tf.paragraphs[0], str(self.n), 9, MUTED, align=PP_ALIGN.RIGHT)
        return BODY_TOP + (lines - 1) * 0.46

    # -- motif -------------------------------------------------------------
    def node_motif(self, slide, x, y, scale=1.0):
        """Small abstract graph, echoing the figures. Used on dark slides."""
        pts = [(0, 0.62), (1.5, 0), (1.5, 1.3), (3.0, 0.72)]
        pts = [(x + a * scale, y + b * scale) for a, b in pts]
        for i, j in [(0, 1), (0, 2), (1, 3), (2, 3)]:
            c = slide.shapes.add_connector(
                1, Inches(pts[i][0] + 0.42 * scale), Inches(pts[i][1] + 0.16 * scale),
                Inches(pts[j][0]), Inches(pts[j][1] + 0.16 * scale))
            c.line.color.rgb = SLATE
            c.line.width = Pt(1.1)
        for k, (px, py) in enumerate(pts):
            col = OCHRE if k == 1 else SLATE
            rect(slide, px, py, 0.42 * scale, 0.32 * scale, fill=None, line=col, line_w=1.5, adj=0.18)

