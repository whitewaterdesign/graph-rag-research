# LaTeX commands that are set as upright words rather than symbols.
MATH_FUNCS = {"log", "exp", "ln", "max", "min", "arg", "argmax", "argmin", "sin",
              "cos", "tan", "det", "dim", "ker", "deg", "gcd", "sup", "inf"}
UNKNOWN_MATH = set()


def _math_word(name):
    r"""A \command: a symbol, an upright function name, or something we cannot
    render -- the last is collected so the build can report it."""
    if name in MATH_WORDS:
        return MATH_WORDS[name]
    if name not in MATH_FUNCS:
        UNKNOWN_MATH.add(name)
    return name


def _script(body, table, marker):
    """Sub/superscript `body` if every character has a unicode form -- a script
    is all-or-nothing, since a half-converted one ("e_id" -> "e\u1d62d") reads worse
    than the plain fallback."""
    body = re.sub(r"\s+", "", body)
    if body and all(c in table for c in body):
        return "".join(table[c] for c in body)
    return marker + body


def strip_math(text):
    """Inline LaTeX reads as noise on a slide. Render what unicode can express,
    and fall back to readable ASCII for the rest."""
    def one(m):
        body = m.group(1)
        body = (body.replace(r"\{", "\x00").replace(r"\}", "\x01")
                    .replace(r"\|", "\u2016"))          # literal braces and bars
        body = re.sub(r"\\(?:text|mathrm|mathit|mathbf|mathcal|mathbb|mathsf"
                      r"|boldsymbol|operatorname)\s*\{(.*?)\}", r"\1", body)
        body = re.sub(r"\\left|\\right|\\!|\\,|\\;|\\:|\\ ", " ", body)
        body = re.sub(r"\\([a-zA-Z]+)", lambda w: _math_word(w.group(1)), body)
        # Single-character scripts first: a braced script that cannot be rendered
        # falls back to "_id", and the single-char rule would then eat its "_i".
        body = re.sub(r"_(\w)", lambda g: _script(g.group(1), SUBSCRIPTS, "_"), body)
        body = re.sub(r"\^(\w)", lambda g: _script(g.group(1), SUPERSCRIPTS, "^"), body)
        body = re.sub(r"_\{(.*?)\}", lambda g: _script(g.group(1), SUBSCRIPTS, "_"), body)
        body = re.sub(r"\^\{(.*?)\}", lambda g: _script(g.group(1), SUPERSCRIPTS, "^"), body)
        body = body.replace("{", "").replace("}", "")
        body = body.replace("\x00", "{").replace("\x01", "}")
        return re.sub(r"\s+", " ", body).strip()
    return re.sub(r"\$(.+?)\$", one, text)



def plain(text):
    """clean_inline with emphasis markers removed, for single-run targets such as
    slide titles, which are styled as a whole and cannot carry mixed runs."""
    return re.sub(r"\*{1,2}|(?<![\w\\])_(?=\S)|(?<=\S)_(?![\w])", "", clean_inline(text))


def clean_inline(text):
    """Normalise a run of inline markdown to plain text."""
    text = re.sub(r"\[@([\w:\-]+)\]", lambda m: f"({CITES.get(m.group(1), m.group(1))})", text)
    text = strip_math(text)
    text = text.replace("''", '"').replace("`", "")
    return re.sub(r"\s+", " ", text).strip()


#  **bold**  |  *italic*  |  _italic_ -- the underscore form only between word
#  boundaries, so it never fires inside an identifier such as e_id or top_k.
EMPHASIS = re.compile(r"\*\*(.+?)\*\*"
                      r"|(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)"
                      r"|(?<![\w\\])_(?!\s)(.+?)(?<!\s)_(?![\w])")


def runs_of(text):
    """Split inline markdown into (text, bold, italic) runs."""
    text = clean_inline(text)
    out, pos = [], 0
    for m in EMPHASIS.finditer(text):
        if m.start() > pos:
            out.append((text[pos:m.start()], False, False))
        if m.group(1) is not None:
            out.append((m.group(1), True, False))
        else:
            out.append((m.group(2) if m.group(2) is not None else m.group(3), False, True))
        pos = m.end()
    if pos < len(text):
        out.append((text[pos:], False, False))
    return out or [(text, False, False)]


def parse_markdown(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    blocks, i = [], 0
    while i < len(lines):
        raw = lines[i]
        line = raw.strip()

        if not line:
            i += 1
            continue

        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            blocks.append(dict(t="h", level=len(m.group(1)), text=plain(m.group(2))))
            i += 1
            continue

        if line.startswith("```"):
            lang = line[3:].strip()
            i += 1
            buf = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            blocks.append(dict(t="code", lang=lang, text="\n".join(buf)))
            continue

        if line.startswith(">"):
            buf = []
            while i < len(lines) and lines[i].strip().startswith(">"):
                buf.append(re.sub(r"^>\s?", "", lines[i].strip()))
                i += 1
            blocks.append(dict(t="quote", text=" ".join(buf).strip()))
            continue

        m = re.match(r"^!\[(.*?)\]\((.+?)\)\s*$", line)
        if m:
            blocks.append(dict(t="img", alt=m.group(1).strip(), src=m.group(2).strip()))
            i += 1
            continue

        if line.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s:\-|]+\|$", lines[i + 1].strip()):
            def cells(s):
                return [c.strip() for c in s.strip().strip("|").split("|")]
            head = cells(line)
            i += 2
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(cells(lines[i]))
                i += 1
            blocks.append(dict(t="table", head=head, rows=rows))
            continue

        if LIST_RE.match(line):
            items = []
            while i < len(lines):
                cur = lines[i].strip()
                m = LIST_RE.match(cur) if cur else None
                if m:
                    indent = len(lines[i]) - len(lines[i].lstrip())
                    items.append(dict(text=m.group(2), level=min(indent // 3, 2),
                                      ordered=m.group(1)[-1] == "."))
                elif cur and items and not re.match(r"^(#{1,6}\s|```|\||!\[)", cur):
                    items[-1]["text"] += " " + cur      # wrapped continuation line
                else:
                    break
                i += 1
            for it in items:
                it["text"] = clean_inline(it["text"])
            blocks.append(dict(t="bullets", items=items))
            continue

        buf = []
        while i < len(lines) and lines[i].strip() and not re.match(
                r"^(#{1,6}\s|```|\||!\[|>|[-*+]\s|\d+[.)]\s)", lines[i].strip()):
            buf.append(lines[i].strip())
            i += 1
        blocks.append(dict(t="para", text=" ".join(buf)))
    return blocks


def block_text_len(b):
    if b["t"] == "para":
        return len(b["text"])
    if b["t"] == "quote":
        return len(b["text"])
    if b["t"] == "bullets":
        return sum(len(x["text"]) for x in b["items"])
    return 999


