    def cover(self, src):
        """A ready-made title graphic, edge to edge. It already carries the deck
        title, so nothing is drawn over it."""
        s = self.new(dark=True)
        path = os.path.join(ROOT, src)
        pic = s.shapes.add_picture(path, 0, 0, width=Inches(SW))
        if pic.height < Inches(SH):        # cover the slide, never letterbox it
            pic._element.getparent().remove(pic._element)
            pic = s.shapes.add_picture(path, 0, 0, height=Inches(SH))
        pic.left = Emu(int((Inches(SW) - pic.width) / 2))
        pic.top = Emu(int((Inches(SH) - pic.height) / 2))

