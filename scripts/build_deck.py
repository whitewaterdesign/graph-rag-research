BIB_FIELDS = ("title", "author", "year", "eprint", "booktitle", "journal", "url")
LIST_RE = re.compile(r"^([-*+]|\d+[.)])\s+(.*)$")
VENUE_STOPWORDS = {"on", "of", "the", "for", "and", "in", "a"}


def parse_bib():
    """Read refs.bib into a record per entry. Values must not contain braces."""
    if not os.path.exists(BIB):
        return []
    parts = re.split(r"@(\w+)\s*\{", open(BIB, encoding="utf-8").read())[1:]
    out = []
    for etype, body in zip(parts[0::2], parts[1::2]):
        rec = {"type": etype.lower(), "key": body.split(",", 1)[0].strip()}
        for f in BIB_FIELDS:
            m = re.search(rf"\b{f}\s*=\s*\{{(.*?)\}}\s*,?\s*(?:\n|$)", body, re.S | re.I)
            rec[f] = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
        out.append(rec)
    return out


BIB_RECORDS = parse_bib()


def surnames_of(author):
    """Surnames from a bibtex author field, in either 'Ada Lovelace' or
    'Lovelace, Ada' form."""
    out = []
    for name in (a.strip() for a in author.split(" and ")):
        if not name:
            continue
        out.append(name.split(",")[0].strip() if "," in name else name.split()[-1])
    return out


def load_citations():
    """Map bibtex keys to a short 'Author et al., year' label."""
    out = {}
    for rec in BIB_RECORDS:
        s = surnames_of(rec["author"])
        label = f"{s[0]} et al." if s else rec["key"]
        if s and rec["year"]:
            label += f", {rec['year']}"
        out[rec["key"]] = label
    return out


CITES = load_citations()


def _norm_title(t):
    return re.sub(r"[^a-z0-9]", "", t.lower())


def reference_meta(rec):
    """The line under a reference: authors, venue, year, arXiv id."""
    venue = rec["booktitle"] or rec["journal"]
    if len(venue) > 40:   # long venue names read better as their initials
        ini = "".join(w[0] for w in re.findall(r"[A-Za-z]+", venue)
                      if w.lower() not in VENUE_STOPWORDS)
        venue = ini.upper() if len(ini) >= 3 else venue
    s = surnames_of(rec["author"])
    author = "" if not s else (s[0] if len(s) == 1 else
                               " & ".join(s) if len(s) == 2 else f"{s[0]} et al.")
    bits = [b for b in (author, venue, rec["year"]) if b]
    if rec["eprint"]:
        bits.append("arXiv:" + rec["eprint"])
    return "  \u00b7  ".join(bits)


def bibliography_entries():
    """Unique references, alphabetical by first author. A paper held twice --
    typically a preprint plus its published version -- collapses to one entry
    keeping the longer title, the earlier year, and both venues."""
    merged = []
    for rec in sorted(BIB_RECORDS, key=lambda r: -len(r["title"])):
        norm = _norm_title(rec["title"])
        hit = next((m for m in merged
                    if _norm_title(m["title"]).startswith(norm)
                    or norm.startswith(_norm_title(m["title"]))), None)
        if hit is None:
            merged.append(dict(rec))
            continue
        for f in ("eprint", "booktitle", "journal", "url"):
            hit[f] = hit[f] or rec[f]
        if rec["year"] and rec["year"] < hit["year"]:
            hit["year"] = rec["year"]
    return sorted(merged, key=lambda r: ((surnames_of(r["author"]) or [""])[0].lower(),
                                         r["year"]))


