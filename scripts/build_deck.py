def drop_final_stop(text):
    """Remove a full stop closing a sentence, but keep one that belongs to an
    abbreviation, so 'Han et al.' does not become 'Han et al'."""
    if not text.endswith("."):
        return text
    last = text[:-1].split()[-1] if text[:-1].split() else ""
    return text if len(last.rstrip(".")) <= 3 else text[:-1]


def image_title_and_caption(b):
    """A caption short enough to be a title becomes one; never show both."""
    cap = caption_for(b)
    if not cap:
        print(f"  ! no caption for {b['src']} -- give it alt text in the markdown, "
              f"or add it to CAPTIONS in scripts/build_deck.py", file=sys.stderr)
        return "Figure", ""
    if len(cap) <= 82:
        return drop_final_stop(cap), ""
    head = re.split(r"[:;,]", cap)[0].strip()
    return (head if 8 <= len(head) <= 82 else "Figure"), cap


def eyebrow_of(sec, u):
    """Section name, plus the heading this unit sits under -- so a subsection
    reads as one of its parent's options rather than a peer of it."""
    bits = [sec["title"] or ""] + ([u["parent"]] if u.get("parent") else [])
    return "  \u00b7  ".join(b for b in bits if b)


def emit_unit(deck, eyebrow, u):
    """Turn one H3 unit (or a section intro) into slides."""
    head = u["head"] or eyebrow
    text_blocks = [b for b in u["blocks"] if b["t"] in ("para", "bullets", "quote")]
    visuals = [b for b in u["blocks"] if b["t"] in ("img", "table", "code")]

    cards = bold_led_cards(u) if u["head"] else None
    if cards:
        deck.pair(eyebrow, u["head"], cards)
        text_blocks = []

    steps = steps_block(u) if u["head"] and not cards else None
    if steps:
        i = u["blocks"].index(steps)
        before = [b for b in u["blocks"][:i] if b["t"] in ("para", "bullets", "quote")]
        after = [b for b in u["blocks"][i + 1:] if b["t"] in ("para", "bullets", "quote")]
        # a short run-in line ("...takes the following steps:") heads the steps
        # slide rather than trailing the slide before it.
        lede = ""
        if before and before[-1]["t"] == "para" and block_text_len(before[-1]) < 120:
            lede = before.pop()["text"]
        if before:
            deck.content(eyebrow, head, before)
        deck.steps(eyebrow, head, steps["items"], lede)
        if after:
            deck.content(eyebrow, head + " (cont.)", after)
        text_blocks = []

    # A one-line intro sitting in front of a figure reads better as a lede on
    # that figure than as a near-empty slide of its own.
    lede = ""
    if (text_blocks and visuals
            and all(b["t"] == "para" for b in text_blocks)
            and sum(block_text_len(b) for b in text_blocks) < 150):
        lede = " ".join(b["text"] for b in text_blocks)
        text_blocks = []

    if text_blocks:
        deck.content(eyebrow, head, text_blocks)

    for b in u["blocks"]:
        if b["t"] == "img":
            title, cap = image_title_and_caption(b)
            deck.figure(eyebrow, title, b["src"], cap, lede=lede)
            lede = ""
        elif b["t"] == "table":
            deck.table(eyebrow, head, b["head"], b["rows"])
        elif b["t"] == "code":
            src = next((v for k, v in MERMAID_MAP.items() if k in b["text"]), None)
            if src:
                deck.figure(eyebrow, "The GraphRAG pipeline", src,
                            "How a query moves through the four stages", lede=lede)
                lede = ""
            else:
                print(f"  ! unmapped {b['lang'] or 'code'} block skipped "
                      f"(add it to MERMAID_MAP in scripts/build_deck.py)", file=sys.stderr)


def main():
    blocks = parse_markdown(SRC)
    doc_title, sections = build_structure(blocks)

    source = ""
    for b in blocks:
        if b["t"] == "para":
            m = re.search(r"\(([^)]*\d{4})\)", clean_inline(b["text"]))
            if m:
                source = "Source: " + m.group(1)
            break

    # An image placed above the H1 is a ready-made title graphic: it becomes the
    # opening slide in place of the generated one, and gets no figure slide.
    cover = blocks[0] if blocks and blocks[0]["t"] == "img" else None
    if cover and not os.path.exists(os.path.join(ROOT, cover["src"])):
        print(f"  ! missing cover image {cover['src']}", file=sys.stderr)
        cover = None
    if cover:
        for sec in sections:
            for u in sec["units"]:
                if cover in u["blocks"]:
                    u["blocks"].remove(cover)
        for sec in sections:
            sec["units"] = [u for u in sec["units"] if u["blocks"]]
        sections = [s for s in sections if s["units"]]

    deck = Deck(doc_title)
    if cover:
        deck.cover(cover["src"])
    else:
        deck.title_slide(DECK_SUBTITLE, source)

    last_para = None
    if CLOSING_FROM_LAST_PARA:
        for sec in reversed(sections):
            for u in reversed(sec["units"]):
                paras = [b for b in u["blocks"] if b["t"] == "para"]
                if paras and len(u["blocks"]) > 1:
                    last_para = paras[-1]["text"]
                    u["blocks"].remove(paras[-1])   # shown on the closing slide instead
                    break
            if last_para:
                break

    idx = 0
    for si, sec in enumerate(sections):
        eyebrow = sec["title"] or doc_title
        if sec["title"]:
            idx += 1
            deck.divider(idx, sec["title"])

        i, units = 0, sec["units"]
        while i < len(units):
            u = units[i]

            # A heading whose body is only an intro line and which is followed by
            # its own subsections is the title for them, not a card beside them.
            title, lede = None, ""
            sibs = [x for x in units[i + 1:] if x["level"] == u["level"] + 1]
            if (u["head"] and len(sibs) >= 2 and all(is_card_unit(x) for x in sibs[:2])
                    and all(b["t"] == "para" for b in u["blocks"])
                    and sum(block_text_len(b) for b in u["blocks"]) < 330):
                title = u["head"]
                lede = " ".join(b["text"] for b in u["blocks"])
                i += 1
                u = units[i]

            if is_card_unit(u):
                lvl, group = u["level"], []
                while (i < len(units) and is_card_unit(units[i])
                       and units[i]["level"] == lvl and len(group) < 6):
                    group.append(units[i])
                    i += 1
                if len(group) == 1 and not title:
                    emit_unit(deck, eyebrow_of(sec, group[0]), group[0])
                else:
                    deck.cards(eyebrow, title or sec["title"] or "Overview", group, lede)
                continue

            emit_unit(deck, eyebrow_of(sec, u), u)
            i += 1

    if last_para:
        deck.closing(last_para)

    refs = bibliography_entries()
    if refs:
        deck.bibliography(refs, doc_title)

    if UNKNOWN_MATH:
        print("  ! no symbol for " + ", ".join("\\" + c for c in sorted(UNKNOWN_MATH))
              + " -- add it to MATH_WORDS in scripts/build_deck.py", file=sys.stderr)

    deck.save()
    print(f"wrote {OUT}  ({len(deck.prs.slides.__iter__.__self__._sldIdLst)} slides)")


if __name__ == "__main__":
    main()
