# structure: sections -> units
# =============================================================================
def build_structure(blocks):
    doc_title, sections, cur = "Deck", [], dict(title=None, blocks=[])
    for b in blocks:
        if b["t"] == "h" and b["level"] == 1:
            doc_title = b["text"]
        elif b["t"] == "h" and b["level"] == 2:
            if cur["blocks"] or cur["title"]:
                sections.append(cur)
            cur = dict(title=b["text"], blocks=[])
        else:
            cur["blocks"].append(b)
    sections.append(cur)

    for s in sections:
        units, u = [], dict(head=None, level=2, parent=None, blocks=[])
        stack = []                      # (level, heading) of the open ancestors
        for b in s["blocks"]:
            if b["t"] == "h" and b["level"] >= 3:
                if u["blocks"] or u["head"]:
                    units.append(u)
                while stack and stack[-1][0] >= b["level"]:
                    stack.pop()
                u = dict(head=b["text"], level=b["level"],
                         parent=stack[-1][1] if stack else None, blocks=[])
                stack.append((b["level"], b["text"]))
            else:
                u["blocks"].append(b)
        units.append(u)
        s["units"] = [x for x in units if x["blocks"]]
    return doc_title, [s for s in sections if s["units"]]


def is_card_unit(u):
    if not u["head"]:
        return False
    if any(b["t"] in ("img", "table", "code") for b in u["blocks"]):
        return False
    return sum(block_text_len(b) for b in u["blocks"]) <= CARD_MAX_CHARS


def bold_led_cards(u):
    """A bold lead-in opens a card; the prose and lists that follow are its body,
    whether the lead-in is inline ("**Heuristics** - uses...") or a label on its
    own line. None if the unit is not shaped that way. Figures in the same unit
    are ignored here -- emit_unit gives each of them its own slide anyway."""
    cards, lede, kicker = [], "", ""
    for b in u["blocks"]:
        if b["t"] in ("img", "table", "code"):
            continue
        if b["t"] == "para" and b["text"].lstrip().startswith("**"):
            rs = runs_of(b["text"])
            head = rs[0][0].strip(" -–—:") if rs and rs[0][1] else ""
            # Keep the body as runs, not flat text -- emphasis inside a card body
            # ("**Tuple-based**, returning facts as...") has to survive.
            body = list(rs[1:] if head else rs)
            if body:
                t, bo, it = body[0]
                body[0] = (t.lstrip(" -–—:"), bo, it)
            cards.append(dict(head=head, body=body, bullets=[]))
        elif b["t"] == "quote":
            kicker = b["text"]           # "> ..." closes the slide under the cards
        elif not cards:
            # one short opening line is allowed, and heads the slide
            if b["t"] == "para" and not lede and block_text_len(b) < 330:
                lede = b["text"]
            else:
                return None
        elif b["t"] == "para":
            cards[-1]["body"] += [(" ", False, False)] + runs_of(b["text"])
        elif b["t"] == "bullets":
            cards[-1]["bullets"] += b["items"]
        else:
            return None
    for c in cards:
        c["body"] = [r for r in c["body"] if r[0]]
        c["text"] = "".join(t for t, _, _ in c["body"]).strip()
    if not 2 <= len(cards) <= 4:
        return None
    return dict(cards=cards, lede=lede, kicker=kicker)


def steps_block(u):
    """A flat numbered list of 4+ items -> a numbered steps slide."""
    for b in u["blocks"]:
        if (b["t"] == "bullets" and len(b["items"]) >= 4
                and all(i["ordered"] and i["level"] == 0 for i in b["items"])):
            return b
    return None


